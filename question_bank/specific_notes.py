def specific_note(q):
    topic=q["topic"]
    answer=q["answer"]
    question=q["question"]
    if topic=="国家与大洲":
        country=re.split(r"主要位于|位于",question,1)[0]
        return COUNTRY_LOCATION.get(country,"")
    if topic=="地名省区":
        city=question.removeprefix("下列城市").split("位于")[0]
        return CITY_FEATURES.get(city,"")
    if topic=="动物识别":
        return ANIMAL_FACTS.get(answer,"")
    if topic=="植物分类":
        return PLANT_FACTS.get(answer,"")
    if topic=="天气工具":
        return WEATHER_TOOLS.get(answer,"")
    if topic=="天气与观察":
        return WEATHER_EVENTS.get(answer,"")
    if topic=="植物部位":
        return PLANT_PARTS.get(answer,"")
    if topic=="古诗作者":
        m=re.search(r"《([^》]+)》",question)
        return POEM_NOTES.get(m.group(1),"") if m else ""
    return ""
