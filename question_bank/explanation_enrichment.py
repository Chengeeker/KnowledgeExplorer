# Exact answer lookup is deliberately restricted to topics where the same word has the
# same meaning; e.g. "水" can mean many unrelated things and is omitted.
ANSWER_TIP_TOPICS = {
    "感官与身体","物品用途","动物识别","动物分类","植物分类",
    "化学与物理基础","古诗作者","传统文学深入",
    "省级行政区首府","国家与首都","国家与大洲",
}
BOILERPLATE = "对应的正确答案是"
JUDGMENT_MARK = "由原判断题转换为同知识点四选一题。"

def _special(q):
    individual=specific_note(q)
    if individual:
        return individual
    answer=q["answer"]
    if q["topic"] in ANSWER_TIP_TOPICS:
        return ANSWER_INSIGHTS.get(answer,"")
    # A few units and definitions occur across several related topics.
    if q["topic"] in ("统计与概率","化学与物理基础"):
        return ANSWER_INSIGHTS.get(answer,"")
    return ""

def _map_tip(q):
    topic=q["topic"]
    if topic == "国家与首都":
        return TOPIC_TIPS[topic]
    if topic == "国家与大洲":
        return "可以先在世界地图上找到题中的国家，再对照周围陆地与海洋的位置判断大洲。"
    if topic in ("省级行政区首府","地名省区"):
        return TOPIC_TIPS[topic]
    return TOPIC_TIPS.get(topic, "辨认这一知识点时，可以留意题目中的关键特征，并与身边实际观察到的现象对照。")

def enrich(q):
    original=q["explanation"].strip()
    source=original
    converted=original.startswith(JUDGMENT_MARK)
    if converted:
        original=original.replace(JUDGMENT_MARK,"",1).removeprefix("原解析：")
        original=re.sub(r"^原问题的答案是[“\"].+?[”\"]。","",original).strip()
    boilerplate=BOILERPLATE in original
    special=_special(q)
    if boilerplate:
        # Original just repeated the question and answer; throw it away in display.
        original=""
    # Always favor a question-specific factual note when available.
    if special and (boilerplate or converted or len(original)<24):
        upgraded=(original+" " if original and special not in original else "")+special
    elif boilerplate:
        upgraded=_map_tip(q)
    elif len(original)<24 or converted:
        note=_map_tip(q)
        upgraded=(original + " " + note).strip()
    else:
        upgraded=original
    if len(upgraded)<25:
        upgraded=(upgraded+" "+_map_tip(q)).strip()
    upgraded=re.sub(r"\s+"," ",upgraded)
    assert upgraded and BOILERPLATE not in upgraded and JUDGMENT_MARK not in upgraded
    return upgraded, ("source" if upgraded==source else "enhanced")
